CREATE TABLE IF NOT EXISTS User (
	id INT NOT NULL UNIQUE PRIMARY KEY AUTO_INCREMENT,
	username CHAR(32) NOT NULL UNIQUE,
	email CHAR(64) NOT NULL,
	passwordHash TEXT(256) NOT NULL,
	passwordSalt CHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS Pet (
	id INT NOT NULL UNIQUE PRIMARY KEY AUTO_INCREMENT,
	ownerID INT NOT NULL,
	name VARCHAR(64) NOT NULL,
	CONSTRAINT ownerFK FOREIGN KEY(ownerID) REFERENCES User(id)
);

CREATE TABLE IF NOT EXISTS PetAppearance (
	petID INT NOT NULL UNIQUE,
	speciesID CHAR(32) NOT NULL,
	mainColor INT NOT NULL,
	secondaryColor INT NOT NULL,
	variant INT NOT NULL DEFAULT(0),
	CONSTRAINT petFK FOREIGN KEY(petID) REFERENCES Pet(id),
	CONSTRAINT speciesFK FOREIGN KEY(speciesID) REFERENCES Species(id)
);

-- For Species, the id is a char
CREATE TABLE IF NOT EXISTS Species (
	id CHAR(32) NOT NULL UNIQUE PRIMARY KEY,
	genus VARCHAR(128) NOT NULL,
	species VARCHAR(128) NOT NULL
)